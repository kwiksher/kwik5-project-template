#!/usr/bin/env python3
"""Emit Solar2D/Kwik layer files from ``Photoshop/<book>/<page>/page.layers.yaml``.

This is the headless replacement for the Photoshop UXP "publish" step
(``docs/PAGE-GENERATION-PLAN.md`` §B, §F2).  One YAML drives both outputs:

    page.layers.yaml -> create_layered_psd.py -> page.psd + png/<layer>.png
                     -> layers2lua.py        -> components/<page>/layers/*.lua

Geometry contract (§C), verified against
``Solar2D/lua_modules/kwiksher/kwik/components/kwik/layer_image.lua``:

    imageWidth  = layerProps.width  * scale      -- scale clamps to 0.25
    mX          = layerProps.x      * scale + (contentWidth - 480*scale/0.25)/2

so ``layerProps`` are **PSD pixels verbatim** in a 4x space, ``x``/``y`` are the
layer **centre**, and ``xScale``/``yScale`` must never appear (the guard clamps
1 -> 0.25, which is what made ten prop permutations render identically).

Usage
-----
    python3 Scripts/layers2lua.py p1                 # one page
    python3 Scripts/layers2lua.py --all              # every Photoshop/<book>/*/page.layers.yaml
    python3 Scripts/layers2lua.py --all --check      # verify, write nothing
    python3 Scripts/layers2lua.py --all --check --force

``--check`` compares the emitted text with what is on disk (and audits every
existing ``layers/*.lua`` for a forbidden ``xScale``) and exits 1 on a diff.
"""

from __future__ import annotations

import argparse
import filecmp
import glob
import os
import shutil
import sys
from typing import Any

import yaml

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
from paths import ASSETS_DIR, BOOK, BOOK_DIR, COMPONENTS_DIR  # noqa: E402
sys.path.insert(0, os.path.join(REPO_ROOT, "Scripts"))
from paths import PAGES_DIR  # noqa: E402  — single source of truth for the page tree

# Book order, front cover first, back cover last (§D page map).
PAGE_ORDER = [
    "cover",
    "p1",
    "p2",
    "p3",
    "p4",
    "p5",
    "p6",
    "p7",
    "p8",
    "back",
]
BLEED_NAMES = {"bg", "background"}
BANNED_KEYS = ("xScale", "yScale")


# --------------------------------------------------------------------------- #
# helpers
# --------------------------------------------------------------------------- #
def die(msg: str, code: int = 2):
    print(f"error: {msg}", file=sys.stderr)
    raise SystemExit(code)


def rel(path: str) -> str:
    try:
        return os.path.relpath(path, REPO_ROOT)
    except ValueError:
        return path


def resolve(path: str, base: str) -> str:
    if os.path.isabs(path):
        return path
    for root in (base, REPO_ROOT):
        candidate = os.path.normpath(os.path.join(root, path))
        if os.path.exists(candidate):
            return candidate
    return os.path.normpath(os.path.join(REPO_ROOT, path))


def lua_str(value: str) -> str:
    return '"' + str(value).replace("\\", "\\\\").replace('"', '\\"') + '"'


def num(value: Any) -> str:
    """Render a number the way the Kwik exporter does (no trailing .0)."""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    f = float(value)
    if f.is_integer():
        return str(int(f))
    return repr(f)


def load_yaml(path: str) -> dict[str, Any]:
    with open(path, "r", encoding="utf-8") as fh:
        data = yaml.safe_load(fh)
    if not data:
        die(f"{path}: empty or invalid YAML")
    if isinstance(data, list):
        data = {"layers": data}
    if not isinstance(data.get("layers"), list) or not data["layers"]:
        die(f"{path}: missing 'layers:' list")
    return data


# --------------------------------------------------------------------------- #
# layer emission
# --------------------------------------------------------------------------- #
LAYER_TEMPLATE = """\
-- $weight={weight}
--
-- generated by Scripts/layers2lua.py from {source} -- do not edit by hand;
-- edit the YAML and re-emit.  layerProps are PSD pixels verbatim (x/y are the
-- layer centre); setProps applies x0.25 and the content-centre offset.
-- No per-axis scale fields: layerProps are PSD pixels verbatim (plan §C.3).
local M = require("components.kwik.layer_image").new()

local layerProps = {{
  blendMode = {blend!r},
  height    = {height},
  width     = {width},
  kind      = {kind!r},
  name      = {name},
  type      = "png",
  x         = {x},
  y         = {y},
  alpha     = {alpha},
  anchorX   = 0.5,
  anchorY   = 0.5,
  rotation  = 0,
  shapedWith = "",
}}

M.attachToEdge   = ""
M.layerAsBg      = false
M.isSharedAsset  = false

M:setProps(layerProps)

function M:init(UI)
  if not self.isSharedAsset then
    self.imagePath = UI.page .. self.imageName
  end
end

function M:create(UI)
  local sceneGroup = UI.sceneGroup
  if not self.isSharedAsset then
    self.imagePath = UI.page .. self.imageName
  end
  local obj = self:createImage(UI)
  if obj == nil then return end

  obj.anchorX = layerProps.anchorX
  obj.anchorY = layerProps.anchorY
  obj.rotation = layerProps.rotation or 0
  obj.shapedWith = layerProps.shapedWith

  obj.layerIndex = #UI.layers + 1
  UI.layers[obj.layerIndex] = obj
  sceneGroup[obj.name] = obj
end

function M:didShow(UI)
end

function M:didHide(UI)
end

function M:destroy(UI)
end

function M.getProps()
  return layerProps
end

return M
"""

PAGE_TEMPLATE = """\
-- generated by Scripts/layers2lua.py from {source} -- do not edit by hand.
local sceneName = ...
--
local model = {{
  components = {{
    layers = {{
{layers}
    }},
    audios = {{
    }},
    groups = {{ }},
    timers = {{ }},
    variables = {{ }},
    joints = {{ }},
    page = {{ }},
  }},
  commands = {{ }},
  onInit = function(scene) end,
}}
--
return require('controller.scene').new(sceneName, model)
"""

INDEX_TEMPLATE = """\
-- generated by Scripts/layers2lua.py -- do not edit by hand.
--
local scenes = {{
{pages}
}}
return scenes
"""


def layer_kind(layer: dict) -> str:
    if layer.get("text") is not None:
        return "pixel"  # captions are baked to PNG by create_layered_psd.py
    return "pixel"


def render_layer_lua(page: str, layer: dict, weight: int, source: str,
                     yaml_dir: str) -> str:
    name = str(layer["name"])
    alpha = layer.get("opacity", 1)
    return LAYER_TEMPLATE.format(
        weight=weight,
        source=source,
        blend=str(layer.get("blendMode", layer.get("blend", "normal"))),
        height=num(int(layer["height"])),
        width=num(int(layer["width"])),
        kind=layer_kind(layer),
        name=lua_str(name),
        x=num(layer["x"]),
        y=num(layer["y"]),
        alpha=num(float(alpha)),
    )


def render_page_lua(page: str, layers: list[dict], source: str) -> str:
    blocks = []
    for layer in layers:
        name = str(layer["name"])
        blocks.append(f"      {{ {name} = {{ }} }},")
    return PAGE_TEMPLATE.format(source=source, layers="\n".join(blocks))


def render_index_lua(pages: list[str]) -> str:
    return INDEX_TEMPLATE.format(
        pages="\n".join(f'  "{page}",' for page in pages)
    )


# --------------------------------------------------------------------------- #
# asset staging
# --------------------------------------------------------------------------- #
def asset_source(page: str, layer: dict, yaml_dir: str) -> str:
    """Where the PNG for this layer comes from.

    Always prefer the **processed** layer PNG written by create_layered_psd.py:
    that is the one with the chroma key applied, fitted to the layer box and with
    opacity baked in.  Shipping a raw ``image:`` source (a character sprite, a
    page plate) would draw its flat backdrop as a rectangle around the figure.
    """
    processed = os.path.join(PAGES_DIR, page, "png", f"{layer['name']}.png")
    if os.path.exists(processed):
        return processed
    if layer.get("image"):
        return resolve(str(layer["image"]), yaml_dir)
    return processed


def check_layer(layer: dict) -> list[str]:
    problems = []
    name = layer.get("name")
    if not name:
        return ["a layer has no name"]
    for banned in BANNED_KEYS:
        if banned in layer:
            problems.append(
                f"{name}: {banned} is forbidden in layerProps (§C.3) — "
                "layerProps are PSD pixels verbatim"
            )
    for req in ("x", "y", "width", "height"):
        if req not in layer:
            problems.append(f"{name}: missing '{req}'")
    if any(k not in layer for k in ("x", "y", "width", "height")):
        return problems
    w, h = int(layer["width"]), int(layer["height"])
    if w <= 0 or h <= 0:
        problems.append(f"{name}: width/height must be positive")
    if w % 2 or h % 2:
        problems.append(f"{name}: odd size {w}x{h}")
    return problems


def bleed_warnings(layer: dict, canvas: dict) -> list[str]:
    """Layers that leave the canvas: a warning, unless it is a background."""
    if not all(k in layer for k in ("x", "y", "width", "height")):
        return []
    cw, ch = int(canvas["width"]), int(canvas["height"])
    w, h = int(layer["width"]), int(layer["height"])
    left = round(float(layer["x"]) - w / 2)
    top = round(float(layer["y"]) - h / 2)
    right, bottom = left + w, top + h
    if left >= 0 and top >= 0 and right <= cw and bottom <= ch:
        return []
    name = str(layer.get("name", ""))
    if layer.get("bleed") or name in BLEED_NAMES:
        return []  # intentional overscan
    return [
        f"{name}: ({left},{top})-({right},{bottom}) leaves the {cw}x{ch} canvas"
    ]


# --------------------------------------------------------------------------- #
# one page
# --------------------------------------------------------------------------- #
def process_page(page: str, check: bool, force: bool) -> tuple[int, int, list[str]]:
    """Returns (written, unchanged, problems).  In check mode nothing is written."""
    yaml_path = os.path.join(PAGES_DIR, page, "page.layers.yaml")
    if not os.path.exists(yaml_path):
        return 0, 0, [f"{page}: no {rel(yaml_path)}"]

    spec = load_yaml(yaml_path)
    canvas = {"width": 1920, "height": 1280}
    canvas.update(spec.get("canvas") or {})
    layers: list[dict] = spec["layers"]
    yaml_dir = os.path.dirname(os.path.abspath(yaml_path))
    rel_source = rel(yaml_path)

    problems: list[str] = []
    for layer in layers:
        problems += check_layer(layer)
        problems += bleed_warnings(layer, canvas)
    if problems:
        return 0, 0, [f"{page}: {p}" for p in problems]

    # ---- assets -----------------------------------------------------------
    asset_dir = os.path.join(ASSETS_DIR, page)
    for layer in layers:
        name = str(layer["name"])
        src = asset_source(page, layer, yaml_dir)
        dst = os.path.join(asset_dir, f"{name}.png")
        if not os.path.exists(src):
            problems.append(
                f"{page}/{name}: missing PNG {rel(src)} — run "
                f"Scripts/create_layered_psd.py {rel(yaml_path)}"
            )
            continue
        if check:
            if not os.path.exists(dst) or not filecmp.cmp(src, dst, shallow=False):
                problems.append(f"{page}/{name}: asset out of date: {rel(dst)}")
        else:
            os.makedirs(asset_dir, exist_ok=True)
            if not os.path.exists(dst) or not filecmp.cmp(src, dst, shallow=False):
                shutil.copy2(src, dst)
    if problems:
        return 0, 0, problems

    # ---- layer files ------------------------------------------------------
    total = len(layers)
    files: list[tuple[str, str]] = []
    for index, layer in enumerate(layers):
        weight = total - 1 - index  # 0 = front, matches $weight
        text = render_layer_lua(page, layer, weight, rel_source, yaml_dir)
        path = os.path.join(COMPONENTS_DIR, page, "layers", f"{layer['name']}.lua")
        files.append((path, text))

    files.append(
        (
            os.path.join(BOOK_DIR, f"{page}.lua"),
            render_page_lua(page, layers, rel_source),
        )
    )

    written = unchanged = 0
    for path, text in files:
        current = None
        if os.path.exists(path):
            with open(path, "r", encoding="utf-8") as fh:
                current = fh.read()
        if current == text:
            unchanged += 1
            continue
        if check:
            problems.append(f"{page}: out of date: {rel(path)}")
            continue
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(text)
        written += 1
        if not force:
            print(f"  wrote {rel(path)}")

    return written, unchanged, problems


def update_index(available: list[str], check: bool) -> list[str]:
    ordered = [p for p in PAGE_ORDER if p in available]
    ordered += sorted(p for p in available if p not in PAGE_ORDER)
    text = render_index_lua(ordered)
    path = os.path.join(BOOK_DIR, "index.lua")
    if os.path.exists(path):
        with open(path, "r", encoding="utf-8") as fh:
            if fh.read() == text:
                return []
    if check:
        return [f"index.lua out of date (expected: {', '.join(ordered)})"]
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)
    print(f"  wrote {rel(path)}")
    return []


# --------------------------------------------------------------------------- #
# repo-wide guard
# --------------------------------------------------------------------------- #
def audit_no_xscale() -> list[str]:
    """The done criterion: no layerProps anywhere contains xScale."""
    problems = []
    pattern = os.path.join(COMPONENTS_DIR, "**", "layers", "*.lua")
    for path in glob.glob(pattern, recursive=True):
        with open(path, "r", encoding="utf-8") as fh:
            for lineno, line in enumerate(fh, 1):
                stripped = line.strip()
                if stripped.startswith("--"):
                    continue
                if "xScale" in stripped or "yScale" in stripped:
                    problems.append(f"{rel(path)}:{lineno}: {stripped}")
    return problems


def discover_pages() -> list[str]:
    pages = []
    for path in sorted(glob.glob(os.path.join(PAGES_DIR, "*", "page.layers.yaml"))):
        pages.append(os.path.basename(os.path.dirname(path)))
    return [p for p in PAGE_ORDER if p in pages] + [p for p in pages if p not in PAGE_ORDER]


# --------------------------------------------------------------------------- #
# cli
# --------------------------------------------------------------------------- #
def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(
        description="Emit Kwik layer Lua from page.layers.yaml (§F2)",
    )
    parser.add_argument("pages", nargs="*", help="page ids, e.g. p1 cover")
    parser.add_argument(
        "--all", action="store_true", help="every Photoshop/<book>/*/page.layers.yaml"
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="write nothing; exit 1 if anything is out of date",
    )
    parser.add_argument(
        "--force", action="store_true", help="overwrite without printing each file"
    )
    args = parser.parse_args(argv)

    pages = args.pages or (discover_pages() if args.all else [])
    if not pages:
        die("nothing to do: pass page ids or --all")

    mode = "check" if args.check else "emit"
    print(f"layers2lua: {mode} for {', '.join(pages)}")

    all_problems: list[str] = []
    total_written = total_unchanged = 0
    built: list[str] = []
    for page in pages:
        written, unchanged, problems = process_page(page, args.check, args.force)
        total_written += written
        total_unchanged += unchanged
        all_problems += problems
        if not problems:
            built.append(page)
        print(
            f"  {page}: {written} written, {unchanged} unchanged"
            + (f", {len(problems)} problem(s)" if problems else "")
        )

    if built:
        # The book index is the *whole* page list on disk, not the subset this
        # invocation was asked to emit — otherwise emitting one page silently
        # drops every other page from index.lua and the Simulator can no longer
        # show it ("showView ... not found in").
        all_problems += update_index(discover_pages(), args.check)

    xscale = audit_no_xscale()
    if xscale:
        all_problems += ["forbidden xScale/yScale in layerProps:"] + xscale

    if all_problems:
        for problem in all_problems:
            print(f"  FAIL {problem}", file=sys.stderr)
        return 1
    print(f"ok: {total_written} written, {total_unchanged} unchanged")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
