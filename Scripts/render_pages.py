#!/usr/bin/env python3
"""Render a page's background art from its technical model (§H).

Reads ``Photoshop/<book>/<page>/page.model.md`` (generated by ``fountain2pages.py``), which
carries the prompt, the Cast ``subject_ids`` and the generation settings, and
submits one batch still to the Guaardvark backend.  The result lands at
``Photoshop/<book>/<page>/art/bg.png`` at the 1920x1280 safe-area size — the background
overscan is produced deterministically by ``create_layered_psd.py``
(``fit_to: canvas`` + ``extend: mirror``), so nothing essential is ever cropped
and the art is never re-rendered to a second aspect.

Identity comes only from the Cast ``subject_ids`` parsed out of the model; the
LoRA triggers are applied by the backend and never appear in the prompt.

Usage
-----
    python3 Scripts/render_pages.py p4
    python3 Scripts/render_pages.py p4 p5 p6 p7 p8 cover back
    python3 Scripts/render_pages.py --all --force       # re-render everything
    python3 Scripts/render_pages.py p4 --dry-run        # print the request
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
import time
import urllib.error
import urllib.request
from typing import Any

from PIL import Image

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
from book_config import BOOK
sys.path.insert(0, os.path.join(REPO_ROOT, "Scripts"))
from paths import PAGES_DIR  # noqa: E402  — single source of truth for the page tree
DEFAULT_SERVER = os.environ.get("GUAARDVARK_SERVER", "http://127.0.0.1:5055")
SAFE_W, SAFE_H = 1920, 1280
RENDER_W, RENDER_H = 1536, 1024


def die(msg: str, code: int = 2):
    print(f"error: {msg}", file=sys.stderr)
    raise SystemExit(code)


def http_json(url: str, payload: dict | None = None, timeout: float = 60.0) -> dict:
    data = None
    headers = {"Accept": "application/json"}
    if payload is not None:
        data = json.dumps(payload).encode()
        headers["Content-Type"] = "application/json"
    request = urllib.request.Request(url, data=data, headers=headers,
                                     method="POST" if data else "GET")
    try:
        with urllib.request.urlopen(request, timeout=timeout) as response:
            return json.loads(response.read().decode())
    except urllib.error.HTTPError as exc:
        body = exc.read().decode("utf-8", "replace")
        die(f"{url}: HTTP {exc.code}: {body[:400]}", 3)


def parse_model(page: str) -> dict[str, Any]:
    path = os.path.join(PAGES_DIR, page, "page.model.md")
    if not os.path.exists(path):
        die(f"{page}: no {path} — run Scripts/fountain2pages.py")
    text = open(path, encoding="utf-8").read()

    prompt = None
    match = re.search(r"## Prompt\n\n```text\n(.*?)\n```", text, re.S)
    if match:
        prompt = match.group(1).strip()
    if not prompt:
        die(f"{page}: no '## Prompt' fenced block in {path}")

    # Only *character* cast ids go to the backend: an environment subject has no
    # LoRA (and no trigger), so passing its id makes the cast pipeline reject the
    # request. The setting still enters the prompt as text.
    subject_ids: list[int] = []
    chars = re.search(r"## Characters\n(.*?)(?:\n## |\Z)", text, re.S)
    if chars:
        subject_ids = sorted({int(m) for m in re.findall(r"- Cast:\s*(\d+)", chars.group(1))})

    negative_match = re.search(r"^- negative:\s*(.+)$", text, re.M)
    model_match = re.search(r"model:\s*([^\s·]+)", text)
    style_match = re.search(r"style:\s*([^\s·]+)", text)
    return {
        "page": page,
        "prompt": prompt,
        "subject_ids": subject_ids,
        "model": model_match.group(1) if model_match else "zimage-turbo",
        "style": style_match.group(1) if style_match else "artistic",
        "negative_prompt": negative_match.group(1).strip() if negative_match else "",
        "source": os.path.relpath(path, REPO_ROOT),
    }


def out_path(page: str) -> str:
    return os.path.join(PAGES_DIR, page, "art", "bg.png")


def submit(spec: dict, server: str) -> str:
    payload = {
        "prompts": [spec["prompt"]],
        "model": spec["model"],
        "style": spec["style"],
        "width": RENDER_W,
        "height": RENDER_H,
        "auto_enhance": False,
        "negative_prompt": spec.get("negative_prompt", ""),
        "subject_ids": spec["subject_ids"],
        "display_name": f"{BOOK} {spec['page']}",
    }
    response = http_json(server + "/api/batch-image/generate/prompts", payload, timeout=120)
    if not response.get("success") and response.get("status") != "success":
        die(f"{spec['page']}: submit failed: {response}")
    data = response.get("data") or {}
    batch = data.get("batch_id")
    if not batch:
        die(f"{spec['page']}: no batch id in {response}")
    params = data.get("parameters") or {}
    print(
        f"  {spec['page']}: batch {batch} "
        f"{params.get('width')}x{params.get('height')} "
        f"model={params.get('model')} style={params.get('style')} "
        f"auto_enhance={params.get('auto_enhance')} "
        f"subject_ids={spec['subject_ids']}"
    )
    return batch


def poll(batch: str, server: str, timeout: float) -> dict:
    deadline = time.time() + timeout
    last = ""
    while time.time() < deadline:
        data = http_json(f"{server}/api/batch-image/status/{batch}", timeout=60).get("data") or {}
        state = data.get("status", "?")
        line = f"    {batch}: {state} {data.get('completed_images', 0)}/{data.get('total_images', 0)}"
        if line != last:
            print(line, flush=True)
            last = line
        if state in ("completed", "complete", "failed", "cancelled", "cancelled_by_user"):
            return data
        time.sleep(5)
    die(f"batch {batch} did not finish within {timeout:.0f}s")


def first_image(data: dict, server: str, batch: str) -> str:
    images = data.get("images") or []
    candidates: list[str] = []
    for item in images:
        if isinstance(item, str):
            candidates.append(item)
        elif isinstance(item, dict):
            for key in ("path", "filepath", "file", "filename", "url"):
                value = item.get(key)
                if isinstance(value, str) and value:
                    candidates.append(value)
    out_dir = data.get("output_dir")
    if out_dir and os.path.isdir(out_dir):
        # os.walk order is not guaranteed, and every batch writes a small
        # thumbnails/<name>.jpg beside the real images/<name>.png. Collect both,
        # drop the thumbnails when a full-size candidate exists, and take the
        # largest file so a 256 px preview is never mistaken for the render.
        found: list[str] = []
        for root, _dirs, names in os.walk(out_dir):
            for name in sorted(names):
                if name.lower().endswith((".png", ".jpg", ".jpeg", ".webp")):
                    found.append(os.path.join(root, name))
        full = [f for f in found if "thumbnail" not in f.split(os.sep)]
        # If the same stem exists as both .png and .jpg, the .png is the render.
        png_stems = {os.path.splitext(os.path.basename(f))[0]
                     for f in full if f.lower().endswith(".png")}
        full = [f for f in full
                if f.lower().endswith(".png")
                or os.path.splitext(os.path.basename(f))[0] not in png_stems]
        pool = full or found
        pool.sort(key=lambda f: os.path.getsize(f), reverse=True)
        candidates.extend(pool)
    for candidate in candidates:
        if candidate.startswith("http"):
            continue
        if os.path.exists(candidate):
            return candidate
        joined = os.path.join(out_dir or "", os.path.basename(candidate))
        if os.path.exists(joined):
            return joined
    die(f"{batch}: could not find the generated image (status={data.get('status')})")


def install_image(src: str, page: str) -> str:
    dst = out_path(page)
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    with Image.open(src) as im:
        im = im.convert("RGB")
        if im.size != (SAFE_W, SAFE_H):
            im = im.resize((SAFE_W, SAFE_H), Image.LANCZOS)
        im.save(dst)
    print(f"  {page}: wrote {os.path.relpath(dst, REPO_ROOT)} ({SAFE_W}x{SAFE_H})")
    return dst


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("pages", nargs="*")
    parser.add_argument("--all", action="store_true", help="p4..p8, cover, back")
    parser.add_argument("--force", action="store_true", help="re-render even if art exists")
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--server", default=DEFAULT_SERVER)
    parser.add_argument("--timeout", type=float, default=900.0, help="seconds per page")
    parser.add_argument(
        "--subject-ids",
        default=None,
        help="override the model's cast ids (art-direction retry; comma separated)",
    )
    args = parser.parse_args(argv)

    pages = args.pages or (
        ["cover", "p4", "p5", "p6", "p7", "p8", "back"] if args.all else []
    )
    if not pages:
        die("nothing to do: pass page ids or --all")

    for page in pages:
        spec = parse_model(page)
        dst = out_path(page)
        if os.path.exists(dst) and not args.force:
            print(f"  {page}: art exists ({os.path.relpath(dst, REPO_ROOT)}), --force to re-render")
            continue
        if args.dry_run:
            print(f"  {page}: subject_ids={spec['subject_ids']} "
                  f"{RENDER_W}x{RENDER_H} model={spec['model']} style={spec['style']}")
            print(spec["prompt"])
            print()
            continue
        if args.subject_ids is not None:
            spec["subject_ids"] = [
                int(v) for v in re.findall(r"\d+", args.subject_ids)
            ]
        batch = submit(spec, args.server)
        data = poll(batch, args.server, args.timeout)
        if data.get("status") != "completed":
            die(f"{page}: batch ended as {data.get('status')}: {data.get('error')}")
        install_image(first_image(data, args.server, batch), page)

    print("done")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
